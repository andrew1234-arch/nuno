// Embeds docs/METHODOLOGY.md and docs/VALIDATION.md into the static build.
import { readFileSync, writeFileSync } from "node:fs";
const read = (f) => readFileSync(new URL(`../../../docs/${f}`, import.meta.url), "utf8");
writeFileSync(
  new URL("../lib/methodology.generated.ts", import.meta.url),
  `// Generated by scripts/embed-methodology.mjs from docs/METHODOLOGY.md and docs/VALIDATION.md. Do not edit.\n` +
    `export const METHODOLOGY_MD = ${JSON.stringify(read("METHODOLOGY.md"))};\n` +
    `export const VALIDATION_MD = ${JSON.stringify(read("VALIDATION.md"))};\n`,
);
