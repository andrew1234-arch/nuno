// Regenerates packages/shared/src/feedAbi.ts from the Foundry build output.
import { readFileSync, writeFileSync } from "node:fs";
const out = {};
for (const name of ["NunoFeed", "OrganicGate"]) {
  const j = JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url)));
  out[name] = { abi: j.abi, bytecode: j.bytecode.object };
}
const src = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.
export const nunoFeedAbi = ${JSON.stringify(out.NunoFeed.abi, null, 2)} as const;

export const organicGateAbi = ${JSON.stringify(out.OrganicGate.abi, null, 2)} as const;

export const nunoFeedBytecode = "${out.NunoFeed.bytecode}" as const;
export const organicGateBytecode = "${out.OrganicGate.bytecode}" as const;
`;
writeFileSync(new URL("../packages/shared/src/feedAbi.ts", import.meta.url), src);
console.log("wrote packages/shared/src/feedAbi.ts");
